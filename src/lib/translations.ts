export function getGradeDisplayLabel(
  grade: string | undefined | null,
  t: Translations,
  academicYear?: string
): string {
  const g = String(grade || '').trim();
  if (!g || g === 'All' || g === 'All Grades' || g === 'الكل') {
    return t.common.allGrades;
  }
  if (g === '3rd Secondary' || g === 'الصف الثالث الثانوي') {
    return academicYear ? `${t.common.grade3} (${academicYear})` : t.common.grade3;
  }
  if (g === '2nd Secondary' || g === 'الصف الثاني الثانوي') {
    return t.common.grade2;
  }
  if (g === '1st Secondary' || g === 'الصف الأول الثانوي') {
    return t.common.grade1;
  }
  return g;
}

