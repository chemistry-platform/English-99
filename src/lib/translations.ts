export function formatTemplate(template: string, vars: Record<string, string | number>): string {
  let out = template;
  Object.entries(vars).forEach(([k, v]) => {
    out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  });
  return out;
}

