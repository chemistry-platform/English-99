export type Language = 'ar' | 'en';

export const LANG_STORAGE_KEY = 'platform_lang';

export function getCurrentLanguage(): Language {
  if (typeof window === 'undefined') return 'ar';
  try {
    return localStorage.getItem(LANG_STORAGE_KEY) === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
}

export function getLocaleCode(lang: Language = getCurrentLanguage()): string {
  return lang === 'ar' ? 'ar-EG' : 'en-US';
}

export function applyDocumentLanguage(lang: Language): void {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

