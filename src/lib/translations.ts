interface LanguageContextValue {
  lang: Language;
  isRTL: boolean;
  locale: string;
  t: Translations;
  setLang: (lang: Language) => void;
  toggleLang: () => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => getCurrentLanguage());

  useEffect(() => {
    applyDocumentLanguage(lang);
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
      // ignore storage errors
    }
  }, [lang]);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((prev) => (prev === 'ar' ? 'en' : 'ar'));
  }, []);

  const value = useMemo<LanguageContextValue>(
    () => ({
      lang,
      isRTL: lang === 'ar',
      locale: getLocaleCode(lang),
      t: getTranslations(lang),
      setLang,
      toggleLang,
    }),
    [lang, setLang, toggleLang]
  );

  return React.createElement(LanguageContext.Provider, { value }, children);
};

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (ctx) return ctx;
  const fallbackLang = getCurrentLanguage();
  return {
    lang: fallbackLang,
    isRTL: fallbackLang === 'ar',
    locale: getLocaleCode(fallbackLang),
    t: getTranslations(fallbackLang),
    setLang: () => {},
    toggleLang: () => {},
  };
}
